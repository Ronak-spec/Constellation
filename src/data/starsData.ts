// Generate 450 procedurally realistic background stars across celestial sphere
export function generateBackgroundStarfield(): Star[] {
  const bgStars: Star[] = [];
  const spectralClasses: ('O' | 'B' | 'A' | 'F' | 'G' | 'K' | 'M')[] = [
    'B', 'A', 'A', 'F', 'F', 'G', 'G', 'G', 'K', 'K', 'M', 'M'
  ];

  // Seeded deterministic pseudo-random distribution
  let seed = 42891;
  const rand = () => {
    seed = (seed * 16807) % 2147483647;
    return (seed - 1) / 2147483646;
  };

  for (let i = 0; i < 480; i++) {
    const ra = rand() * 24;
    // Area-preserving sphere distribution for declination
    const sinDec = rand() * 2 - 1;
    const dec = (Math.asin(sinDec) * 180) / Math.PI;
    
    // Magnitude curve (most stars are dim 4.0 - 6.2)
    const mag = 3.6 + Math.pow(rand(), 1.8) * 2.8;
    const sType = spectralClasses[Math.floor(rand() * spectralClasses.length)];

    bgStars.push({
      id: `bg_star_${i}`,
      name: `HIP ${20000 + i * 197}`,
      spectralType: sType,
      mag,
      ra,
      dec,
      distLy: Math.round(50 + rand() * 1800),
      constellationId: 'sky_field',
      color: getSpectralColor(sType),
    });
  }

  return bgStars;
}

export const ALL_SKY_STARS: Star[] = [...PRIMARY_STARS, ...generateBackgroundStarfield()];
